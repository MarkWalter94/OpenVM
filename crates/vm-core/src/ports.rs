//! Ports to external dependencies (ROADMAP 6.1, 6.3).
//!
//! The core performs no I/O: clock, identifier generation, catalog,
//! audit, media inspection and QEMU backend are injected through these traits.
//! The real implementations live in `vm-storage`, `qemu-backend` and
//! `lightvm-service`; tests use fake in-memory implementations.
//!
//! The traits are synchronous: an asynchronous implementation is adapted by the
//! supervisor (for example with a dedicated worker). The recommended path for
//! the backend is the "I/O-free" one of [`crate::Core::begin_dispatch`] /
//! [`crate::Core::finish_dispatch`], which does not hold the core during the
//! backend call; [`VmBackend`] serves helpers and tests.

use lightvm_proto::{
    AuditEvent, BaselineId, DisplayGeometry, GrantId, InputEvent, Label, MediaEntry, MediaId,
    MediaKind, MediaRecord, OperationId, OperationRecord, PublicError, RunEndReason, RunId,
    RunRecord, Screenshot, SessionId, UtcTimestamp, VmId, VmRecord, VmState,
};

use crate::media::{ObservedMediaFacts, VerifiedMedia};

/// UTC clock.
pub trait Clock {
    /// Current instant.
    fn now(&self) -> UtcTimestamp;
}

/// Source of UUID v7 identifiers.
pub trait IdGenerator {
    /// Unix milliseconds and 10 bytes of counter/randomness for the next identifier.
    fn next_parts(&mut self) -> (u64, [u8; 10]);

    /// New [`VmId`].
    fn vm_id(&mut self) -> VmId {
        let (m, r) = self.next_parts();
        VmId::from_unix_millis(m, r)
    }
    /// New [`RunId`].
    fn run_id(&mut self) -> RunId {
        let (m, r) = self.next_parts();
        RunId::from_unix_millis(m, r)
    }
    /// New [`SessionId`].
    fn session_id(&mut self) -> SessionId {
        let (m, r) = self.next_parts();
        SessionId::from_unix_millis(m, r)
    }
    /// New [`GrantId`].
    fn grant_id(&mut self) -> GrantId {
        let (m, r) = self.next_parts();
        GrantId::from_unix_millis(m, r)
    }
    /// New [`MediaId`].
    fn media_id(&mut self) -> MediaId {
        let (m, r) = self.next_parts();
        MediaId::from_unix_millis(m, r)
    }
    /// New [`OperationId`] (for operations generated by the supervisor).
    fn operation_id(&mut self) -> OperationId {
        let (m, r) = self.next_parts();
        OperationId::from_unix_millis(m, r)
    }
    /// New [`BaselineId`].
    fn baseline_id(&mut self) -> BaselineId {
        let (m, r) = self.next_parts();
        BaselineId::from_unix_millis(m, r)
    }
}

/// Persistent catalog (implemented by `vm-storage` on SQLite).
pub trait CatalogStore {
    /// Inserts a new VM.
    fn insert_vm(&mut self, vm: &VmRecord) -> Result<(), PublicError>;
    /// Closes the VM's runs left open (supervisor restart with no surviving
    /// processes); returns how many were closed.
    fn close_open_runs(&mut self, _id: VmId, _reason: RunEndReason) -> Result<u32, PublicError> {
        Ok(0)
    }
    /// `true` if the catalog journal has unfinished intents on the VM
    /// (files being modified or "to be verified"): the VM is not reconciled
    /// automatically.
    fn has_open_intents(&self, _id: VmId) -> Result<bool, PublicError> {
        Ok(false)
    }
    /// Replaces configuration and revision of an existing VM if the
    /// stored revision is `expected_revision`.
    fn update_vm(&mut self, vm: &VmRecord, expected_revision: u64) -> Result<(), PublicError>;
    /// Reads a VM.
    fn get_vm(&self, id: VmId) -> Result<Option<VmRecord>, PublicError>;
    /// Lists the VMs.
    fn list_vms(&self) -> Result<Vec<VmRecord>, PublicError>;
    /// Updates the persisted (indicative) state.
    fn set_persisted_state(&mut self, id: VmId, state: VmState) -> Result<(), PublicError>;
    /// Inserts a media registry entry.
    fn insert_media(&mut self, entry: &MediaEntry) -> Result<(), PublicError>;
    /// Reads a media registry entry.
    fn get_media(&self, id: MediaId) -> Result<Option<MediaEntry>, PublicError>;
    /// Inserts or updates an operation.
    fn upsert_operation(&mut self, op: &OperationRecord) -> Result<(), PublicError>;
    /// Reads an operation.
    fn get_operation(&self, id: OperationId) -> Result<Option<OperationRecord>, PublicError>;
    /// Inserts a run.
    fn insert_run(&mut self, run: &RunRecord) -> Result<(), PublicError>;
    /// Closes a run.
    fn finish_run(
        &mut self,
        id: RunId,
        ended_at: UtcTimestamp,
        reason: RunEndReason,
    ) -> Result<(), PublicError>;
    /// Approved media of the registry.
    fn list_media(&self) -> Result<Vec<MediaRecord>, PublicError> {
        Ok(Vec::new())
    }
    /// Imports the file chosen by the user with the native picker: read-only
    /// managed copy, hash and registry row, with the size limit of `kind`
    /// (ADR-0008). The path is never passed to QEMU. The copy reads the
    /// whole file: it blocks the caller for as long as the copy takes.
    fn import_media(
        &mut self,
        _source: &std::path::Path,
        _kind: MediaKind,
        _declared_origin: &Label,
    ) -> Result<MediaEntry, PublicError> {
        Err(PublicError::unsupported("media import not available"))
    }
    /// Removes an imported medium with its managed copy (journaled by the
    /// storage). The core has checked that no VM configuration uses it.
    fn remove_media(&mut self, _id: MediaId) -> Result<(), PublicError> {
        Err(PublicError::unsupported("media deletion not available"))
    }
    /// Removes a VM without a process with its rows and files (journaled
    /// by the storage).
    fn remove_vm(&mut self, _id: VmId) -> Result<(), PublicError> {
        Err(PublicError::unsupported("VM deletion not available"))
    }
    /// Space used on the host by the VM's files, if measurable.
    fn vm_disk_usage(&self, _id: VmId) -> Option<u64> {
        None
    }
}

/// Destination of audit events, in `seq` order.
pub trait AuditSink {
    /// Appends an event. Events contain no sensitive payloads.
    fn append(&mut self, event: &AuditEvent) -> Result<(), PublicError>;
}

/// Inspection of a managed copy in the media registry: computes hash, size and
/// OS identity on the file opened in a protected way (implemented by `vm-storage` or
/// `qemu-backend`). The comparison with the registry belongs to the core ([`crate::media::verify_media`]).
pub trait MediaInspector {
    /// Observes the managed copy of the entry.
    fn inspect(&mut self, entry: &MediaEntry) -> Result<ObservedMediaFacts, PublicError>;
}

/// QEMU backend with a reduced API (ROADMAP 6.3). Contracts:
/// - `start` returns `Ok` only with a live process and QMP ready;
/// - `shutdown` and `force_stop` return `Ok` only after observing the end of the process;
/// - `force_stop` uses OS primitives and does not depend on QMP (ADR-0009);
/// - no method receives paths or options from the client.
pub trait VmBackend {
    /// Starts run `run_id` with only the media verified by the core.
    fn start(
        &mut self,
        vm: &VmRecord,
        run_id: RunId,
        media: &[VerifiedMedia],
    ) -> Result<(), PublicError>;
    /// Ordinary shutdown.
    fn shutdown(&mut self, vm_id: VmId, run_id: RunId) -> Result<(), PublicError>;
    /// Forced stop of the process tree with OS primitives.
    fn force_stop(&mut self, vm_id: VmId, run_id: RunId) -> Result<(), PublicError>;
    /// Guest reset.
    fn reset(&mut self, vm_id: VmId, run_id: RunId) -> Result<(), PublicError>;
    /// Screenshot within `max_bytes`.
    fn screenshot(
        &mut self,
        vm_id: VmId,
        run_id: RunId,
        max_bytes: u64,
    ) -> Result<Screenshot, PublicError>;
    /// Forwards already authorized input events. Never retried automatically.
    fn send_input(
        &mut self,
        vm_id: VmId,
        run_id: RunId,
        geometry: DisplayGeometry,
        events: &[InputEvent],
    ) -> Result<(), PublicError>;
}
