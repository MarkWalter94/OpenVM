# Builds the x86_64 UEFI firmware for the Windows 11 x64 profile on Windows
# hosts (ADR-0035): edk2-stable202408 OvmfPkgX64 with Secure Boot and TPM2,
# WITHOUT SMM (WHPX has no SMM), plus the local patch in this directory.
#
# Output in <Out>:
#   lightvm-x64-code.fd        firmware code (pflash0, read-only)
#   lightvm-x64-vars-blank.fd  empty variable store
#   lightvm-x64-vars-win.fd    variable store with Secure Boot on: a generated
#                              PK (private key discarded), Microsoft KEK 2011+2023,
#                              Windows-only db (PCA 2011, UEFI CA 2023)
#   SHA256SUMS
#
# Requirements: git, Visual Studio 2022 Build Tools (MSVC x86/x64), NASM,
# ACPICA iasl, Python 3 (with venv/pip). Paths are parameters.
# usage: build.ps1 -Work <dir> -Out <dir> -Python <python.exe> -NasmDir <dir\> -IaslDir <dir\>
param(
  [Parameter(Mandatory)][string]$Work, [Parameter(Mandatory)][string]$Out,
  [Parameter(Mandatory)][string]$Python, [Parameter(Mandatory)][string]$NasmDir,
  [Parameter(Mandatory)][string]$IaslDir, [int]$Jobs = 4,
  [string]$VcVars = 'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars32.bat'
)
$ErrorActionPreference = 'Stop'
$EDK2_TAG = 'edk2-stable202408'
$EDK2_COMMIT = 'b158dad150bf02879668f72ce306445250838201'
$VIRT_FIRMWARE = 'virt-firmware==26.9 --hash=sha256:64d0078e6dd0c82a1df3a97c3cc8a149340068095cf8cfb6beb02005e3194160'
$Here = $PSScriptRoot
New-Item -ItemType Directory -Force $Work, $Out | Out-Null
$Src = Join-Path $Work 'edk2'

if (-not (Test-Path $Src)) {
  git clone -q --depth 1 --branch $EDK2_TAG https://github.com/tianocore/edk2.git $Src
}
if ((git -C $Src rev-parse HEAD) -ne $EDK2_COMMIT) { throw 'unexpected edk2 commit' }
foreach ($m in 'CryptoPkg/Library/OpensslLib/openssl', 'CryptoPkg/Library/MbedTlsLib/mbedtls',
               'BaseTools/Source/C/BrotliCompress/brotli', 'MdeModulePkg/Library/BrotliCustomDecompressLib/brotli',
               'MdePkg/Library/BaseFdtLib/libfdt', 'MdePkg/Library/MipiSysTLib/mipisyst',
               'SecurityPkg/DeviceSecurity/SpdmLib/libspdm') {
  git -C $Src submodule update --init --depth 1 -q $m
}
$patch = Join-Path $Here '0001-OvmfPkgX64-IntrinsicLib-for-DisplayEngineDxe-MSVC.patch'
git -C $Src apply --check $patch 2>$null; if ($LASTEXITCODE -eq 0) { git -C $Src apply $patch }

# BaseTools host tools and the firmware, in one cmd.exe environment.
$bat = Join-Path $Work 'build-ovmf.cmd'
@"
@echo off
call "$VcVars" >nul || exit /b 1
set WORKSPACE=$Src
set EDK_TOOLS_PATH=$Src\BaseTools
set PYTHON_COMMAND=$Python
set NASM_PREFIX=$NasmDir
set IASL_PREFIX=$IaslDir
cd /d $Src || exit /b 2
call edksetup.bat Rebuild VS2019 || exit /b 3
call build -a X64 -t VS2019 -b RELEASE -p OvmfPkg\OvmfPkgX64.dsc -n $Jobs ^
  -D SECURE_BOOT_ENABLE=TRUE -D SMM_REQUIRE=FALSE -D TPM2_ENABLE=TRUE -D TPM2_CONFIG_ENABLE=TRUE ^
  -D TPM1_ENABLE=FALSE -D BUILD_SHELL=FALSE || exit /b 4
"@ | Set-Content -Encoding ascii $bat
cmd /c "`"$bat`" > `"$Work\build.log`" 2>&1"
if ($LASTEXITCODE -ne 0) { throw "edk2 build failed ($LASTEXITCODE), see $Work\build.log" }

$fv = Join-Path $Src 'Build\OvmfX64\RELEASE_VS2019\FV'
Copy-Item "$fv\OVMF_CODE.fd" "$Out\lightvm-x64-code.fd" -Force
Copy-Item "$fv\OVMF_VARS.fd" "$Out\lightvm-x64-vars-blank.fd" -Force

# Secure Boot keys with virt-firmware (pinned by hash). The venv sees the
# interpreter's site packages for `cryptography`. virt-firmware's
# --enroll-generate does not work on Windows (it reopens an open temporary
# file), so the PK is generated by gen-pk.py (private key discarded) and
# enrolled with --enroll-cert.
$venv = Join-Path $Work 'venv'
& $Python -m venv --system-site-packages $venv
$req = Join-Path $Work 'virtfw-req.txt'; $VIRT_FIRMWARE | Set-Content -Encoding ascii $req
& "$venv\Scripts\python.exe" -m pip install -q --require-hashes --no-deps --only-binary :all: -r $req
$pk = Join-Path $Work 'pk.der'
& "$venv\Scripts\python.exe" -I (Join-Path $Here 'gen-pk.py') $pk 'LightVM Platform Key'
& "$venv\Scripts\python.exe" -I -m virt.firmware.vars --input "$Out\lightvm-x64-vars-blank.fd" `
  --output "$Out\lightvm-x64-vars-win.fd" `
  --enroll-cert $pk --microsoft-kek all --microsoft-db win11 --secure-boot | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'key enrolment failed' }

Get-ChildItem $Out -Filter 'lightvm-x64-*.fd' | ForEach-Object {
  '{0} *{1}' -f (Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLower(), $_.Name
} | Set-Content -Encoding ascii "$Out\SHA256SUMS"
Get-Content "$Out\SHA256SUMS"
